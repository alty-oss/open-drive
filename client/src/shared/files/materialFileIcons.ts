function getBaseName(name: string) {
  const parts = name.split(/[\\/]/);
  return (parts.at(-1) || name).toLowerCase();
}

function getSpecialFileIcon(name: string) {
  if (name === "package.json" || name === "package-lock.json") return nodejsIcon;
  if (name === "pnpm-lock.yaml") return pnpmIcon;
  if (name === "yarn.lock") return yarnIcon;
  if (name === "bun.lock" || name === "bun.lockb") return bunIcon;
  if (name === ".gitignore" || name === ".gitattributes" || name === ".gitmodules") {
    return gitIcon;
  }
  if (name === ".editorconfig") return editorconfigIcon;
  if (name === ".dockerignore" || name === "compose.yaml" || name === "compose.yml") {
    return dockerIcon;
  }
  if (name.startsWith("docker-compose.")) return dockerIcon;
  if (name === ".env" || name.startsWith(".env.")) return tuneIcon;
  if (name === "tsconfig.json" || (name.startsWith("tsconfig.") && name.endsWith(".json"))) {
    return tsconfigIcon;
  }
  if (name.startsWith("vite.config.")) return viteIcon;
  if (name === "dockerfile" || name.startsWith("dockerfile.")) return dockerIcon;
  if (name === "makefile" || name.startsWith("makefile.")) return makefileIcon;
  if (name === "license" || name.startsWith("license.")) return licenseIcon;
  if (name === "readme" || name.startsWith("readme.")) return readmeIcon;
  if (name.endsWith(".pem") || name.endsWith(".crt") || name.endsWith(".cer")) {
    return certificateIcon;
  }
  return null;
}

export function getMaterialFileIcon(name: string, isFolder = false) {
  const baseName = getBaseName(name);

  if (isFolder) {
    return folderIcons[baseName] || folderIcon;
  }

  const specialIcon = getSpecialFileIcon(baseName);
  if (specialIcon) return specialIcon;

  const parts = baseName.split(".");
  for (let index = 1; index < parts.length; index += 1) {
    const extension = parts.slice(index).join(".");
    const icon = extensionIcons[extension];
    if (icon) return icon;
  }

  return fileIcon;
}
